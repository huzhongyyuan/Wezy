const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('lane', {
  getState: () => ipcRenderer.invoke('state:get'),
  setState: (s) => ipcRenderer.invoke('state:set', s),
  pickDir: () => ipcRenderer.invoke('dialog:pickDir'),
  ptyCreate: (o) => ipcRenderer.invoke('pty:create', o),
  ptyWrite: (id, data) => ipcRenderer.send('pty:write', { id, data }),
  ptyResize: (id, cols, rows) => ipcRenderer.send('pty:resize', { id, cols, rows }),
  ptyKill: (id) => ipcRenderer.invoke('pty:kill', { id }),
  ptyStatuses: () => ipcRenderer.invoke('pty:statuses'),
  onPtyStatus: (cb) => ipcRenderer.on('pty:status', (_e, p) => cb(p)),
  ptyList: () => ipcRenderer.invoke('pty:list'),
  onPtyData: (cb) => ipcRenderer.on('pty:data', (_e, p) => cb(p)),
  onPtyExit: (cb) => ipcRenderer.on('pty:exit', (_e, p) => cb(p)),
  runDiagnostics: () => ipcRenderer.invoke('diag:run'),
  getUsage: (days) => ipcRenderer.invoke('usage:get', days),
  openPath: (p) => ipcRenderer.invoke('shell:open', p),
  openExternal: (u) => ipcRenderer.invoke('shell:openExternal', u),
  listProfiles: () => ipcRenderer.invoke('profiles:list'),
  saveProfile: (p) => ipcRenderer.invoke('profiles:save', p),
  removeProfile: (id) => ipcRenderer.invoke('profiles:remove', id),
  activateProfile: (id) => ipcRenderer.invoke('profiles:activate', id),
  testProfile: (p) => ipcRenderer.invoke('profiles:test', p),
  filePath: (f) => { try { return webUtils.getPathForFile(f); } catch { return ''; } },
  saveImage: (data, ext) => ipcRenderer.invoke('clip:saveImage', { data, ext }),
  listSessions: () => ipcRenderer.invoke('sessions:list'),
  removeSession: (o) => ipcRenderer.invoke('session:remove', o),
  archiveCodexSession: (o) => ipcRenderer.invoke('codex:archive', o),
  listCodexSessions: () => ipcRenderer.invoke('codex:sessions'),
  sessionTitles: (cwds) => ipcRenderer.invoke('sessions:titles', cwds),
  sessionBindings: () => ipcRenderer.invoke('sessions:bindings'),
  teamMe: () => ipcRenderer.invoke('profiles:me'),
  platform: process.platform,
});
