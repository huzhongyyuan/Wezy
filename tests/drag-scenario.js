(async () => {
  const wait = ms => new Promise(r => setTimeout(r, ms));
  await wait(200);
  const checks = [];
  const check = (name, pass) => { checks.push({ name, pass }); if (!pass) throw Error(name); };
  state.projects = Array.from({length: 32}, (_, i) => ({id: 'c' + i, kind: 'claude', name: 'Session ' + i, cwd: '/tmp'}));
  renderProjects();
  const panel = $('#projects').closest('.panel.grow');
  const row = id => $$('.projects li').find(el => el.dataset.projectId === id);
  let data;
  const event = (el, type, x = 0, y = 0) => el.dispatchEvent(new DragEvent(type, {bubbles: true, cancelable: true, clientX: x, clientY: y, dataTransfer: data}));
  const start = el => { data = new DataTransfer(); event(el, 'dragstart'); };
  const over = (el, x, y) => event(el, 'dragover', x, y);
  const end = el => event(el, 'dragend');
  const r = panel.getBoundingClientRect(), x = r.left + 40;
  panel.scrollTop = panel.scrollHeight;
  const source = row('c31'), initial = panel.scrollTop;
  check('long list overflows', initial > 500);
  start(source); over(panel, x, r.top + 2);
  await wait(300);
  const intermediate = panel.scrollTop;
  check('stationary pointer scrolls upward', intermediate < initial - 50);
  await wait(300);
  check('continues without additional dragover events', panel.scrollTop < intermediate - 50);
  await wait(2300);
  check('bottom session can travel to top', panel.scrollTop === 0 && source.isConnected);
  const first = row('c0'), f = first.getBoundingClientRect();
  event(first, 'drop', x, f.top + 2); end(source);
  check('drop persists last session before first', state.projects[0].id === 'c31');
  check('drop clears animation and markers', projectDragScroll === null && !$('.drop-before, .drop-after'));
  start(row('c31')); over(panel, x, r.bottom - 2); await wait(300);
  check('bottom edge scrolls downward', panel.scrollTop > 50);
  over(panel, x, (r.top + r.bottom) / 2); await wait(60);
  const center = panel.scrollTop; await wait(200);
  check('center does not scroll', panel.scrollTop === center);
  over(document.body, r.right + 20, r.bottom - 2); await wait(200);
  check('outside container does not scroll', panel.scrollTop === center);
  end(row('c31')); const stopped = panel.scrollTop; await wait(200);
  check('cancelled drag stops scrolling', panel.scrollTop === stopped && !projectDragScroll);
  panel.scrollTop = panel.scrollHeight;
  const lastId = state.projects.at(-1).id;
  for (let i = 0; i < 18; i++) row(lastId).querySelector('.order-up').click();
  const moved = row(lastId).getBoundingClientRect();
  check('arrow moves keep session visible', moved.top >= r.top - 1 && moved.bottom <= r.bottom + 1);
  for (const p of state.projects) await openSession(p.id);
  const refs = [...terms], bar = $('#tabs');
  bar.scrollLeft = bar.scrollWidth;
  const br = bar.getBoundingClientRect(), tab = bar.lastElementChild, left = bar.scrollLeft;
  check('tabs overflow', left > 0);
  start(tab); over(bar, br.left + 2, br.top + 20); await wait(300);
  check('horizontal tab edge scrolls too', bar.scrollLeft < left - 50);
  window.dispatchEvent(new Event('blur')); const blurred = bar.scrollLeft; await wait(200);
  check('window blur stops scrolling', !projectDragScroll && bar.scrollLeft === blurred);
  end(tab);
  check('sorting preserves terminal objects', refs.every(([id, rec]) => terms.get(id) === rec));
  return {scope: 'Real Electron renderer with fixture IPC and DOM drag events; no real PTYs or user state', checks};
})()
